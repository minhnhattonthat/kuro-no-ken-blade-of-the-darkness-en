"""gen_scenes.py: write tools/debug/scenes_data.lua (static data warp.lua needs) from the unpacked original.

    python -X utf8 tools/debug/gen_scenes.py

- zones[map script] = event-zone ids the map script registers (op 0x52 first value), in order;
- eve[map] = {[zone id] = {x, y}}: zone midpoints from each BEP's .EVE second table (same units as the player
  object's x/y at 0x80094dfc), so warp.lua can stand the player at one of the loaded map's zones;
- areas[area] = values of the area's progress variable (0x82 + area number) its dispatcher tests.
Format notes: docs/re/scenes.md.
"""
import struct
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import scn  # noqa: E402
from pad import split_em  # noqa: E402

ORIG = Path("work/orig/mps")


def eve_zones(bep):
    e = dict(split_em(bep.read_bytes())).get(".EVE")
    n1, n2 = struct.unpack_from("<HH", e, 0)
    out = {}
    for i in range(n1, n1 + n2):
        _, x1, y1, x2, y2, zid = struct.unpack_from("<6H", e, 4 + 12 * i)
        out.setdefault(zid, ((x1 + x2) // 2, (y1 + y2) // 2))
    return out


def script_ops(f):
    b = f.read_bytes()
    base = scn.base_of(f.stem)
    ops, _ = scn.walk(b, base)
    return ops


def main():
    lines = ["-- generated by tools/debug/gen_scenes.py from the original disc; do not edit", "local D = {}"]
    lines.append("D.zones = {")
    for f in sorted((ORIG / "SCN").glob("*.SCN")):
        ids = []
        for a, (op, out, _) in sorted(script_ops(f).items()):
            if op == 0x52 and out[0][1][0] == 0 and out[0][1][1] not in ids:
                ids.append(out[0][1][1])
        if ids:
            lines.append(f'  ["{f.stem.lower()}"] = {{ {", ".join(map(str, ids))} }},')
    lines.append("}")
    lines.append("D.eve = {")
    for f in sorted((ORIG / "BEP").glob("*.BEP")):
        z = eve_zones(f)
        body = ", ".join(f"[{k}] = {{ {x}, {y} }}" for k, (x, y) in sorted(z.items()))
        lines.append(f'  ["{f.stem.lower()}"] = {{ {body} }},')
    lines.append("}")
    lines.append("D.areas = {")
    areas = [f for f in sorted((ORIG / "SCN").glob("*.SCN"))
             if len(f.stem) == 5 and f.stem[:2].isdigit() and f.stem not in ("00IPL", "99CMN")]
    for f in areas:
        n = int(f.stem[:2])
        var = 0x82 + n
        copies, vals = set(), set()
        for a, (op, out, _) in sorted(script_ops(f).items()):
            if op == 0x1e and out[1][1] == var:
                copies.add(out[0][1])
            if 0x0d <= op <= 0x18 and out[0][1] in ({var} | copies) and not (op - 0x0d) & 1:
                vals.add(out[1][1])
            if op == 0x08 and out[0][1] in ({var} | copies):
                vals.update(range(out[2][1]))
        lines.append(f'  ["{f.stem.lower()}"] = {{ var = 0x{var:x}, vals = {{ {", ".join(map(str, sorted(vals)))} }} }},')
    lines.append("}")
    lines.append("D.area_order = { " + ", ".join(f'"{f.stem.lower()}"' for f in areas) + " }")
    lines.append("return D")
    Path("tools/debug/scenes_data.lua").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print("wrote tools/debug/scenes_data.lua")


if __name__ == "__main__":
    main()
